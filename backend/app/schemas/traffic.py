from pydantic import BaseModel
from typing import Literal

class HealthResponse(BaseModel):
    status: str = "ok"
    service: str = "netsight-api"
    model_loaded: bool = False
    model_version: str | None = None

class ValidationResponse(BaseModel):
    valid: bool = True
    filename: str
    row_count: int
    columns: list[str]
    preview: list[dict[str, str]]
    schema_name: str = "network-metrics-v1"
    message: str = "CSV schema and numeric features validated. No ML predictions were generated by this endpoint."

class Prediction(BaseModel):
    row_id: int
    label: Literal["normal", "anomalous"]
    anomaly_score: float

class PredictionPreview(Prediction):
    features: dict[str, float]

class AnalysisCounts(BaseModel):
    normal: int
    anomalous: int

class AnalysisResponse(BaseModel):
    analysis_id: str
    source_type: Literal["uploaded_csv"] = "uploaded_csv"
    filename: str
    model_version: str
    threshold: float
    total_flows: int
    counts: AnalysisCounts
    predictions: list[Prediction]
    preview: list[PredictionPreview]
    score_definition: str
    message: str
